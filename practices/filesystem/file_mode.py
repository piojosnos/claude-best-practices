# --------------------------------------------------------------------------------
# The file mode: whether a file on disk has its owner execute bit
# --------------------------------------------------------------------------------

from pathlib import Path


# --------------------------------------------------------------------------------
# Constants
# --------------------------------------------------------------------------------

_OWNER_EXEC_BIT = 0o100


# --------------------------------------------------------------------------------
# Reading the mode
# --------------------------------------------------------------------------------

def is_executable(path: Path) -> bool:
    return bool(path.stat().st_mode & _OWNER_EXEC_BIT)
